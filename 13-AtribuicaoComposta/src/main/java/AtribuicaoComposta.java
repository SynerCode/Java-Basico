public class AtribuicaoComposta {

    public static void main(String[] args) {
        
        // +=
        int a = 10;
        int b = 20;
        //a = a + b;
        a += b;
        System.out.print("\nResultado : " + a);
        
        // -=
        int c = 10;
        int d = 20;
        //c = c - d;
        c -= d;
        System.out.print("\nResultado : " + c);
        
        // *=
        int e = 10;
        int f = 20;
        //e = e * f;
        e *= f;
        System.out.print("\nResultado : " + e);
        
        // /=
        int g = 10;
        int h = 20;
        //g = g / h;
        g /= h;
        System.out.print("\nResultado : " + g);
        
        // %=
        int i = 10;
        int j = 20;
        //i = i % j;
        i %= j;
        System.out.print("\nResultado : " + i);
          
    }
}
